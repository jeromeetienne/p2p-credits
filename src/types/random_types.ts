/**
 * A function that returns a number greater than or equal to 0 and lower than 1.
 *
 * The library never calls the global random number generator. Every policy that needs randomness receives this
 * function instead, so a simulation can replace it by a seeded generator and reproduce a run exactly.
 */
export type RandomNumberFn = () => number;
